def _character_class(ranges):
    return "[" + "".join(
        re.escape(chr(low)) if low == high else f"{re.escape(chr(low))}-{re.escape(chr(high))}"
        for low, high in ranges
    ) + "]"


_PICTOGRAPH = _character_class(EXTENDED_PICTOGRAPHIC)
_VARIATION_SELECTOR = "\uFE0F?"
_SKIN_TONE = "[\U0001F3FB-\U0001F3FF]"
_TAG_FLAG = "[\U000E0020-\U000E007E]+\U000E007F"
_KEYCAP = "[0-9#*]\uFE0F?\u20E3"
_FLAG = "[\U0001F1E6-\U0001F1FF]{2}"
_ELEMENT = f"(?:{_PICTOGRAPH}{_VARIATION_SELECTOR}(?:{_SKIN_TONE}|{_TAG_FLAG})?|{_KEYCAP}|{_FLAG})"
ONE_EMOJI = re.compile(f"{_ELEMENT}(?:\u200D{_ELEMENT})*")


def one_emoji(value):
    """Is `value` one emoji — rather than a word, a row of them, or nothing?"""
    return 0 < len(value) <= LONGEST_EMOJI and ONE_EMOJI.fullmatch(value) is not None
