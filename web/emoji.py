"""What counts as one emoji, for the settings form.

The picker lets somebody type or paste whatever their keyboard offers, so the
emoji field is free text, and free text needs a test. The standard library
cannot split graphemes and knows none of the emoji properties, so this is the
grammar of one emoji written out over Unicode's own `Extended_Pictographic`
ranges (emoji-data.txt, Unicode 17.0). Those ranges include the reserved space
new emoji are assigned to, so next year's emoji pass without a change here.

One emoji is an element, or elements joined by zero-width joiners:

    element = pictograph [variation selector] [skin tone | tag flag]
            | keycap: one of 0-9 # * [variation selector] U+20E3
            | flag: two regional indicators

"🐶🐱" is two elements with nothing joining them, and is refused. The same two with
a joiner typed between them would pass and render as two — the price of
accepting joined sequences without a list of them, and a small one. The browser
applies the same grammar (`looksLikeEmoji` in `emoji-picker.js`) before offering
what was typed, so the dialog never offers what Save would refuse.
"""

